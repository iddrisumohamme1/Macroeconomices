/**
 * Computes exact dates for any trading week (Monday - Friday)
 * based on baseDate and weekOffset (-1 for Previous, 0 for Current, +1 for Next).
 */
export function getTradingWeekDates(baseDate: Date = new Date(), weekOffset = 0) {
  const d = new Date(baseDate);
  const day = d.getDay(); // 0 is Sunday, 1 is Monday ... 6 is Saturday

  let mondayOffset = 1 - day;
  if (day === 0) {
    mondayOffset = 1;
  } else if (day === 6) {
    mondayOffset = 2;
  }

  // Apply week offset (-1 for previous week, 0 for current week, +1 for next week)
  mondayOffset += weekOffset * 7;

  const monday = new Date(d);
  monday.setDate(d.getDate() + mondayOffset);

  const days: {
    dayOfWeek: 'Mon' | 'Tue' | 'Wed' | 'Thu' | 'Fri';
    dateLabel: string;
    fullDateStr: string;
    isToday: boolean;
    isPast: boolean;
  }[] = [];

  const dayNames: ('Mon' | 'Tue' | 'Wed' | 'Thu' | 'Fri')[] = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri'];
  const todayIso = new Date(baseDate).toISOString().split('T')[0];

  for (let i = 0; i < 5; i++) {
    const cur = new Date(monday);
    cur.setDate(monday.getDate() + i);

    const monthStr = cur.toLocaleDateString('en-US', { month: 'short' });
    const dayNum = cur.getDate();
    const curIso = cur.toISOString().split('T')[0];

    const isToday = curIso === todayIso;
    const isPast = curIso < todayIso;

    const dateLabel = isToday
      ? `Today (${dayNames[i]}, ${monthStr} ${dayNum})`
      : `${dayNames[i]}, ${monthStr} ${dayNum}`;

    days.push({
      dayOfWeek: dayNames[i],
      dateLabel,
      fullDateStr: curIso,
      isToday,
      isPast,
    });
  }

  return days;
}

export function getWeekDateRangeString(baseDate: Date = new Date(), weekOffset = 0): string {
  const weekDays = getTradingWeekDates(baseDate, weekOffset);
  const start = weekDays[0];
  const end = weekDays[4];
  const cleanStart = start.dateLabel.replace(/Today \((.*?)\)/, '$1');
  const cleanEnd = end.dateLabel.replace(/Today \((.*?)\)/, '$1');
  return `${cleanStart} – ${cleanEnd}`;
}

